"""The screen host agreement a host signs on its private page.

The text is filled in with the host's details. When the host signs, the
exact text they saw is saved on the host record and a copy is emailed to the
owner and to the host.
"""

from datetime import datetime
from zoneinfo import ZoneInfo

from .config import settings
from .models import Host

VERSION = "2026-11-17"
TITLE = "Screen Host Agreement"
COMPANY = "Local Flyer Ads"
COMPANY_LINE = "Local Flyer Ads, 1000 Lafayette Blvd, Suite 100, Bridgeport, CT 06605, (475) 258 8963, localflyerads.com"


def _local(dt: datetime) -> datetime:
    return dt.astimezone(ZoneInfo(settings.timezone))


def details(host: Host) -> list[tuple[str, str]]:
    screens = ", ".join(sorted(d.name for d in host.devices)) or "Assigned at install"
    return [
        ("Host business name", host.business_name),
        ("Business address", host.address or "Not given"),
        ("Owner name", host.name),
        ("Phone", host.phone or "Not given"),
        ("Email", host.email or "Not given"),
        ("Tablet", screens),
        ("Start date", f"{_local(host.created_at):%B %-d, %Y}"),
    ]


def sections(host: Host) -> list[tuple[str, str]]:
    share = host.share_percent
    return [
        ("1. The Tablet",
         f'{COMPANY} ("LFA") owns the digital screen tablet and any mount or cable it provides (the "Tablet"). '
         "LFA lends the Tablet to the Host free of charge for display inside the Host's business. "
         "The Host does not buy or own the Tablet."),
        ("2. What the Host Provides",
         "The Host provides a wall or counter spot where customers can see the screen, a standard power outlet, "
         "and access to the business Wi Fi. The Host agrees to keep the Tablet plugged in and turned on during "
         "business hours."),
        ("3. Ads and Content",
         "LFA controls all ads and content shown on the Tablet. LFA will not run adult, illegal or offensive "
         "content. The Host may ask LFA not to show ads from a direct competitor, and LFA will make reasonable "
         "efforts to honor that request."),
        ("4. Host Revenue Share",
         f"The Host earns {share}% of the ad revenue generated by plays on the Host's Tablet. Earnings are tracked "
         "by the LFA screen system and shown on the Host's private earnings page. Payouts are made monthly through "
         "Stripe to the bank account the Host connects. The Host is responsible for any taxes on its earnings."),
        ("5. Care of the Tablet",
         "The Host agrees not to remove, unplug for long periods, move or tamper with the Tablet, and to tell LFA "
         "if it stops working or is damaged. The Host is not responsible for normal wear or for damage it did not "
         "cause. The Host is responsible for loss or damage caused on purpose or through gross negligence by the "
         "Host or its staff."),
        ("6. Service Visits",
         "LFA may visit during business hours, at a time agreed with the Host, to install, repair, update or "
         "replace the Tablet."),
        ("7. Term and Ending",
         "This agreement starts on the start date above and continues month to month. Either side may end it at "
         "any time with notice by text, email or in person. When it ends, the Host will make the Tablet and its "
         "parts available for LFA to pick up within 7 days, and LFA will pay any earnings owed through the end "
         "date."),
        ("8. General",
         "This is the full agreement between the parties about the Tablet. Changes must be in writing and agreed "
         "by both sides. The Host is not an employee or partner of LFA. This agreement is governed by the laws of "
         "the State of Connecticut."),
        ("9. Electronic Signature",
         "By typing their name and tapping I Agree, the Host signs this agreement electronically. The electronic "
         "signature has the same effect as a handwritten one. LFA accepts the agreement through Tony Cantave, "
         "Founder."),
    ]


def as_text(host: Host) -> str:
    lines = [TITLE, COMPANY_LINE, ""]
    lines += [f"{k}: {v}" for k, v in details(host)]
    for heading, body in sections(host):
        lines += ["", heading, body]
    return "\n".join(lines)


def signature_block(host: Host) -> str:
    when = _local(host.agreement_signed_at) if host.agreement_signed_at else None
    stamp = f"{when:%B %-d, %Y at %-I:%M %p} ({settings.timezone.replace('_', ' ')})" if when else ""
    return "\n".join([
        "",
        "SIGNED",
        f"Host: {host.agreement_signed_name}, Owner, {host.business_name}",
        f"Signed electronically on {stamp}",
        f"From address: {host.agreement_signed_ip or 'unknown'}",
        f"Local Flyer Ads: Tony Cantave, Founder",
        f"Agreement version {host.agreement_version}",
    ])
